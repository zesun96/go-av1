#define BROADCAST_WORD(src, dst) \
	MOVQ src, AX; \
	MOVD AX, dst; \
	PSHUFL $0, dst, dst; \
	PACKSSLW dst, dst

// X1-X5 are scratch, X6 is the current tap weight, X7/X8 are max/min,
// X9 is the current pixel, X10 is INT16_MIN, and X15 is zero.
#define ACCUM_NEIGHBOR(addr, threshold, shift) \
	MOVOU addr, X1; \
	MOVO X1, X2; \
	PCMPEQW X10, X2; \
	MOVO X2, X5; \
	MOVO X2, X3; \
	PAND X9, X3; \
	PANDN X1, X2; \
	POR X3, X2; \
	PMINSW X2, X8; \
	PMAXSW X2, X7; \
	PSUBW X9, X1; \
	MOVO X1, X2; \
	PABSW X1, X1; \
	MOVO X1, X4; \
	PSRAW shift, X4; \
	MOVO threshold, X3; \
	PSUBW X4, X3; \
	PMAXSW X15, X3; \
	PMINSW X3, X1; \
	PSIGNW X2, X1; \
	PANDN X1, X5; \
	MOVO X5, X1; \
	PMULLW X6, X1; \
	PADDW X1, X0

// paddingContiguous8x8SSE41 expands a contiguous 12x12 byte window into the
// 12x12 int16 CDEF scratch layout.
TEXT ·paddingContiguous8x8SSE41(SB), NOSPLIT, $0-24
	MOVQ dst+0(FP), DI
	MOVQ src+8(FP), SI
	MOVQ srcStride+16(FP), R8
	MOVQ $12, CX
padding_row:
	PMOVZXBW (SI), X0
	MOVOU X0, (DI)
	MOVL 8(SI), AX
	MOVD AX, X1
	PMOVZXBW X1, X1
	MOVQ X1, 16(DI)
	ADDQ R8, SI
	ADDQ $24, DI
	DECQ CX
	JNZ padding_row
	RET

// paddingContiguous4x4SSE41 expands the contiguous 8x8 byte window around a
// 4x4 block into the used portion of the 12-wide int16 scratch layout.
TEXT ·paddingContiguous4x4SSE41(SB), NOSPLIT, $0-24
	MOVQ dst+0(FP), DI
	MOVQ src+8(FP), SI
	MOVQ srcStride+16(FP), R8
	MOVQ $8, CX
padding4_row:
	MOVQ (SI), X0
	PMOVZXBW X0, X0
	MOVOU X0, (DI)
	ADDQ R8, SI
	ADDQ $24, DI
	DECQ CX
	JNZ padding4_row
	RET

