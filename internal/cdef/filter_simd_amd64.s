//go:build amd64 && !purego

#include "textflag.h"

#define BROADCAST_WORD(src, dst) \
	MOVQ src, AX; \
	MOVD AX, dst; \
	PSHUFL $0, dst, dst; \
	PACKSSLW dst, dst

// X1-X5 are scratch, X6 is the current tap weight, X7/X8 are max/min,
// X9 is the current pixel, X10 is INT16_MIN, and X15 is zero.
#define ACCUM_NEIGHBOR(addr, threshold, shift) \
	MOVOU addr, X1; \
	MOVO X1, X2; \
	PCMPEQW X10, X2; \
	MOVO X2, X5; \
	MOVO X2, X3; \
	PAND X9, X3; \
	PANDN X1, X2; \
	POR X3, X2; \
	PMINSW X2, X8; \
	PMAXSW X2, X7; \
	PSUBW X9, X1; \
	MOVO X1, X2; \
	PABSW X1, X1; \
	MOVO X1, X4; \
	PSRAW shift, X4; \
	MOVO threshold, X3; \
	PSUBW X4, X3; \
	PMAXSW X15, X3; \
	PMINSW X3, X1; \
	PSIGNW X2, X1; \
	PANDN X1, X5; \
	MOVO X5, X1; \
	PMULLW X6, X1; \
	PADDW X1, X0

// paddingContiguous8x8SSE41 expands a contiguous 12x12 byte window into the
// 12x12 int16 CDEF scratch layout.
TEXT ·paddingContiguous8x8SSE41(SB), NOSPLIT, $0-24
	MOVQ dst+0(FP), DI
	MOVQ src+8(FP), SI
	MOVQ srcStride+16(FP), R8
	MOVQ $12, CX
padding_row:
	PMOVZXBW (SI), X0
	MOVOU X0, (DI)
	MOVL 8(SI), AX
	MOVD AX, X1
	PMOVZXBW X1, X1
	MOVQ X1, 16(DI)
	ADDQ R8, SI
	ADDQ $24, DI
	DECQ CX
	JNZ padding_row
	RET

DATA ·cdefEight<>+0(SB)/8, $0x0008000800080008
DATA ·cdefEight<>+8(SB)/8, $0x0008000800080008
GLOBL ·cdefEight<>(SB), RODATA|NOPTR, $16

// filterPrimary8SSE41 filters eight primary-only CDEF pixels per row.
TEXT ·filterPrimary8SSE41(SB), NOSPLIT, $0-88
	MOVQ dst+0(FP), DI
	MOVQ dstStride+8(FP), R8
	MOVQ src+16(FP), SI
	MOVQ priOff0+24(FP), R10
	SHLQ $1, R10
	MOVQ priOff1+32(FP), R11
	SHLQ $1, R11
	MOVQ h+80(FP), R9

	PXOR X15, X15

	MOVQ threshold+40(FP), AX
	MOVD AX, X14
	PSHUFL $0, X14, X14
	PACKSSLW X14, X14

	MOVQ shift+48(FP), AX
	MOVD AX, X13

	MOVQ tap0+56(FP), AX
	MOVD AX, X12
	PSHUFL $0, X12, X12
	PACKSSLW X12, X12

	MOVQ tap1+64(FP), AX
	MOVD AX, X11
	PSHUFL $0, X11, X11
	PACKSSLW X11, X11

	MOVL $8, AX
	MOVD AX, X10
	PSHUFL $0, X10, X10
	PACKSSLW X10, X10

row:
	PMOVZXBW (DI), X9
	PXOR X0, X0

	// First positive primary tap.
	MOVOU (SI)(R10*1), X1
	PSUBW X9, X1
	MOVO X1, X2
	PABSW X1, X1
	MOVO X1, X4
	PSRAW X13, X4
	MOVO X14, X3
	PSUBW X4, X3
	PMAXSW X15, X3
	PMINSW X3, X1
	PSIGNW X2, X1
	PMULLW X12, X1
	PADDW X1, X0

	// First negative primary tap.
	MOVQ SI, AX
	SUBQ R10, AX
	MOVOU (AX), X1
	PSUBW X9, X1
	MOVO X1, X2
	PABSW X1, X1
	MOVO X1, X4
	PSRAW X13, X4
	MOVO X14, X3
	PSUBW X4, X3
	PMAXSW X15, X3
	PMINSW X3, X1
	PSIGNW X2, X1
	PMULLW X12, X1
	PADDW X1, X0

	// Second positive primary tap.
	MOVOU (SI)(R11*1), X1
	PSUBW X9, X1
	MOVO X1, X2
	PABSW X1, X1
	MOVO X1, X4
	PSRAW X13, X4
	MOVO X14, X3
	PSUBW X4, X3
	PMAXSW X15, X3
	PMINSW X3, X1
	PSIGNW X2, X1
	PMULLW X11, X1
	PADDW X1, X0

	// Second negative primary tap.
	MOVQ SI, AX
	SUBQ R11, AX
	MOVOU (AX), X1
	PSUBW X9, X1
	MOVO X1, X2
	PABSW X1, X1
	MOVO X1, X4
	PSRAW X13, X4
	MOVO X14, X3
	PSUBW X4, X3
	PMAXSW X15, X3
	PMINSW X3, X1
	PSIGNW X2, X1
	PMULLW X11, X1
	PADDW X1, X0

	// (sum + (sum < 0 ? -1 : 0) + 8) >> 4.
	MOVO X0, X1
	PSRAW $15, X1
	PADDW X1, X0
	PADDW X10, X0
	PSRAW $4, X0
	PADDW X9, X0
	PACKUSWB X0, X0
	CMPQ w+72(FP), $4
	JEQ primaryStore4
	MOVQ X0, (DI)
	JMP primaryStored
primaryStore4:
	PEXTRD $0, X0, (DI)
primaryStored:

	ADDQ R8, DI
	ADDQ $24, SI
	DECQ R9
	JNZ row
	RET

// filterCombined8SSE41 filters eight primary+secondary CDEF pixels per row.
TEXT ·filterCombined8SSE41(SB), NOSPLIT, $0-96
	MOVQ dst+0(FP), DI
	MOVQ dstStride+8(FP), R8
	MOVQ src+16(FP), SI
	MOVQ offsets+24(FP), R9
	MOVQ h+88(FP), R11

	PXOR X15, X15
	BROADCAST_WORD(priThreshold+32(FP), X14)
	MOVQ priShift+40(FP), AX
	MOVD AX, X13
	BROADCAST_WORD(secThreshold+64(FP), X12)
	MOVQ secShift+72(FP), AX
	MOVD AX, X11
	MOVL $-32768, AX
	MOVD AX, X10
	PSHUFL $0, X10, X10
	PACKSSLW X10, X10

combinedRow:
	PMOVZXBW (DI), X9
	MOVO X9, X8
	MOVO X9, X7
	PXOR X0, X0

	BROADCAST_WORD(priTap0+48(FP), X6)
	MOVQ 0(R9), R10
	SHLQ $1, R10
	ACCUM_NEIGHBOR((SI)(R10*1), X14, X13)
	MOVQ SI, AX
	SUBQ R10, AX
	ACCUM_NEIGHBOR((AX), X14, X13)

	BROADCAST_WORD(priTap1+56(FP), X6)
	MOVQ 8(R9), R10
	SHLQ $1, R10
	ACCUM_NEIGHBOR((SI)(R10*1), X14, X13)
	MOVQ SI, AX
	SUBQ R10, AX
	ACCUM_NEIGHBOR((AX), X14, X13)

	MOVL $2, AX
	MOVD AX, X6
	PSHUFL $0, X6, X6
	PACKSSLW X6, X6
	MOVQ 16(R9), R10
	SHLQ $1, R10
	ACCUM_NEIGHBOR((SI)(R10*1), X12, X11)
	MOVQ SI, AX
	SUBQ R10, AX
	ACCUM_NEIGHBOR((AX), X12, X11)
	MOVQ 24(R9), R10
	SHLQ $1, R10
	ACCUM_NEIGHBOR((SI)(R10*1), X12, X11)
	MOVQ SI, AX
	SUBQ R10, AX
	ACCUM_NEIGHBOR((AX), X12, X11)

	MOVL $1, AX
	MOVD AX, X6
	PSHUFL $0, X6, X6
	PACKSSLW X6, X6
	MOVQ 32(R9), R10
	SHLQ $1, R10
	ACCUM_NEIGHBOR((SI)(R10*1), X12, X11)
	MOVQ SI, AX
	SUBQ R10, AX
	ACCUM_NEIGHBOR((AX), X12, X11)
	MOVQ 40(R9), R10
	SHLQ $1, R10
	ACCUM_NEIGHBOR((SI)(R10*1), X12, X11)
	MOVQ SI, AX
	SUBQ R10, AX
	ACCUM_NEIGHBOR((AX), X12, X11)

	MOVO X0, X1
	PSRAW $15, X1
	PADDW X1, X0
	PADDW ·cdefEight<>(SB), X0
	PSRAW $4, X0
	PADDW X9, X0
	PMAXSW X8, X0
	PMINSW X7, X0
	PACKUSWB X0, X0
	CMPQ w+80(FP), $4
	JEQ combinedStore4
	MOVQ X0, (DI)
	JMP combinedStored
combinedStore4:
	PEXTRD $0, X0, (DI)
combinedStored:

	ADDQ R8, DI
	ADDQ $24, SI
	DECQ R11
	JNZ combinedRow
	RET

// filterSecondary8SSE41 filters four or eight secondary-only CDEF pixels.
TEXT ·filterSecondary8SSE41(SB), NOSPLIT, $0-64
	MOVQ dst+0(FP), DI
	MOVQ dstStride+8(FP), R8
	MOVQ src+16(FP), SI
	MOVQ offsets+24(FP), R9
	MOVQ h+56(FP), R11

	PXOR X15, X15
	BROADCAST_WORD(threshold+32(FP), X14)
	MOVQ shift+40(FP), AX
	MOVD AX, X13
	MOVL $-32768, AX
	MOVD AX, X10
	PSHUFL $0, X10, X10
	PACKSSLW X10, X10

secondaryRow:
	PMOVZXBW (DI), X9
	MOVO X9, X8
	MOVO X9, X7
	PXOR X0, X0

	MOVL $2, AX
	MOVD AX, X6
	PSHUFL $0, X6, X6
	PACKSSLW X6, X6
	MOVQ 0(R9), R10
	SHLQ $1, R10
	ACCUM_NEIGHBOR((SI)(R10*1), X14, X13)
	MOVQ SI, AX
	SUBQ R10, AX
	ACCUM_NEIGHBOR((AX), X14, X13)
	MOVQ 8(R9), R10
	SHLQ $1, R10
	ACCUM_NEIGHBOR((SI)(R10*1), X14, X13)
	MOVQ SI, AX
	SUBQ R10, AX
	ACCUM_NEIGHBOR((AX), X14, X13)

	MOVL $1, AX
	MOVD AX, X6
	PSHUFL $0, X6, X6
	PACKSSLW X6, X6
	MOVQ 16(R9), R10
	SHLQ $1, R10
	ACCUM_NEIGHBOR((SI)(R10*1), X14, X13)
	MOVQ SI, AX
	SUBQ R10, AX
	ACCUM_NEIGHBOR((AX), X14, X13)
	MOVQ 24(R9), R10
	SHLQ $1, R10
	ACCUM_NEIGHBOR((SI)(R10*1), X14, X13)
	MOVQ SI, AX
	SUBQ R10, AX
	ACCUM_NEIGHBOR((AX), X14, X13)

	MOVO X0, X1
	PSRAW $15, X1
	PADDW X1, X0
	PADDW ·cdefEight<>(SB), X0
	PSRAW $4, X0
	PADDW X9, X0
	PACKUSWB X0, X0
	CMPQ w+48(FP), $4
	JEQ secondaryStore4
	MOVQ X0, (DI)
	JMP secondaryStored
secondaryStore4:
	PEXTRD $0, X0, (DI)
secondaryStored:

	ADDQ R8, DI
	ADDQ $24, SI
	DECQ R11
	JNZ secondaryRow
	RET
