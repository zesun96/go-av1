	PACKUSWB X0, X0
	MOVQ X0, (DI)(CX*1)
	ADDQ $8, CX
	CMPQ CX, R9
	JL vcol
	ADDQ $256, SI
	ADDQ R8, DI
	DECQ R10
	JNZ vrow
	RET
