	MOVQ (R11), X8
	PMOVSXBW X8, X8
	MOVO X8, X9
	PSHUFL $0x00, X9, X9
	MOVO X8, X10
	PSHUFL $0x55, X10, X10
	MOVO X8, X11
	PSHUFL $0xaa, X11, X11
	MOVO X8, X12
	PSHUFL $0xff, X12, X12
	MOVO ·vRound512<>(SB), X13

vrow:
	XORQ CX, CX
vcol:
	MOVOU 0(SI)(CX*2), X0
	MOVOU 256(SI)(CX*2), X1
	MOVO X0, X2
	PUNPCKLWL X1, X0
	PUNPCKHWL X1, X2
	PMADDWL X9, X0
	PMADDWL X9, X2

	MOVOU 512(SI)(CX*2), X3
	MOVOU 768(SI)(CX*2), X4
	MOVO X3, X5
	PUNPCKLWL X4, X3
	PUNPCKHWL X4, X5
	PMADDWL X10, X3
	PMADDWL X10, X5
	PADDL X3, X0
	PADDL X5, X2

	MOVOU 1024(SI)(CX*2), X3
	MOVOU 1280(SI)(CX*2), X4
	MOVO X3, X5
	PUNPCKLWL X4, X3
	PUNPCKHWL X4, X5
	PMADDWL X11, X3
	PMADDWL X11, X5
	PADDL X3, X0
	PADDL X5, X2

	MOVOU 1536(SI)(CX*2), X3
	MOVOU 1792(SI)(CX*2), X4
	MOVO X3, X5
	PUNPCKLWL X4, X3
	PUNPCKHWL X4, X5
	PMADDWL X12, X3
	PMADDWL X12, X5
