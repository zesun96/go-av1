// Horizontal 8-tap pass. Each iteration produces eight signed Q4 samples.
TEXT ·filter8TapHorizontalSSE41(SB), NOSPLIT, $0-48
	MOVQ dst+0(FP), DI
	MOVQ src+8(FP), SI
	MOVQ srcStride+16(FP), R8
	MOVQ w+24(FP), R9
	MOVQ h+32(FP), R10
	MOVQ filter+40(FP), R11

	MOVQ (R11), X8
	MOVO X8, X9
	PSHUFB ·hCoeff01<>(SB), X9
	MOVO X8, X10
	PSHUFB ·hCoeff23<>(SB), X10
	MOVO X8, X11
	PSHUFB ·hCoeff45<>(SB), X11
	MOVO X8, X12
	PSHUFB ·hCoeff67<>(SB), X12
	MOVO ·hRound2<>(SB), X13

hrow:
	XORQ CX, CX
hcol:
	MOVQ -3(SI)(CX*1), X0
	MOVQ 4(SI)(CX*1), X6
	PSLLDQ $8, X6
	POR X6, X0
	MOVO X0, X1
	PSHUFB ·hData01<>(SB), X1
	PMADDUBSW X9, X1
	MOVO X0, X2
	PSHUFB ·hData23<>(SB), X2
	PMADDUBSW X10, X2
	PADDW X2, X1
	MOVO X0, X2
	PSHUFB ·hData45<>(SB), X2
	PMADDUBSW X11, X2
	PADDW X2, X1
	PSHUFB ·hData67<>(SB), X0
	PMADDUBSW X12, X0
	PADDW X0, X1
	PADDW X13, X1
	PSRAW $2, X1
	MOVOU X1, (DI)(CX*2)
	ADDQ $8, CX
	CMPQ CX, R9
	JL hcol
	ADDQ R8, SI
	ADDQ $256, DI
	DECQ R10
	JNZ hrow
	RET

// Vertical 8-tap pass over the fixed 128-sample intermediate stride.
TEXT ·filter8TapVerticalSSE41(SB), NOSPLIT, $0-48
