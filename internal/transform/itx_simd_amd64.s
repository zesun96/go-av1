// dct8Batch4SSE41 performs four independent int32 DCT8 transforms. Each
// transform position is 8 int32 values apart; the pointer selects four lanes.
TEXT ·dct8Batch4SSE41(SB), NOSPLIT, $64-16
	MOVQ dst+0(FP), DI
	MOVQ src+8(FP), SI
	MOVOU ·dctMin<>(SB), X13
	MOVOU ·dctMax<>(SB), X14

	// Even DCT4: t0 and t1.
	MOVOU 0(SI), X0
	MOVOU 128(SI), X4
	MOVO X0, X1
	PADDL X4, X0
	PSUBL X4, X1
	PMULLD ·dctK181<>(SB), X0
	PMULLD ·dctK181<>(SB), X1
	PADDL ·dctRound128<>(SB), X0
	PADDL ·dctRound128<>(SB), X1
	PSRAL $8, X0
	PSRAL $8, X1

	// Even DCT4: t2.
	MOVOU 64(SI), X2
	PMULLD ·dctK1567<>(SB), X2
	MOVOU 192(SI), X4
	MOVO X4, X5
	PMULLD ·dctK312<>(SB), X4
	PADDL X4, X2
	PADDL ·dctRound2048<>(SB), X2
	PSRAL $12, X2
	PSUBL X5, X2

	// Even DCT4: t3.
	MOVOU 64(SI), X3
	MOVO X3, X6
	PMULLD ·dctKN312<>(SB), X3
	MOVOU 192(SI), X4
	PMULLD ·dctK1567<>(SB), X4
	PADDL X4, X3
	PADDL ·dctRound2048<>(SB), X3
	PSRAL $12, X3
	PADDL X6, X3

	// Save clipped even outputs E0..E3.
	MOVO X0, X4
	PADDL X3, X4
	PMAXSD X13, X4
	PMINSD X14, X4
	MOVOU X4, 0(SP)
	MOVO X1, X4
	PADDL X2, X4
	PMAXSD X13, X4
	PMINSD X14, X4
	MOVOU X4, 16(SP)
	MOVO X1, X4
	PSUBL X2, X4
	PMAXSD X13, X4
	PMINSD X14, X4
	MOVOU X4, 32(SP)
	PSUBL X3, X0
	PMAXSD X13, X0
	PMINSD X14, X0
	MOVOU X0, 48(SP)

	// Odd t4a.
	MOVOU 32(SI), X4
	PMULLD ·dctK799<>(SB), X4
