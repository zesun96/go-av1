	PADDL X5, X8
	PMAXSD X13, X8
	PMINSD X14, X8
	PSUBL X5, X4
	PMAXSD X13, X4
	PMINSD X14, X4
	MOVO X7, X10
	PADDL X6, X10
	PMAXSD X13, X10
	PMINSD X14, X10
	PSUBL X6, X7
	PMAXSD X13, X7
	PMINSD X14, X7

