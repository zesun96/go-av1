	MOVOU (SI), X0
	PADDL X7, X0
	PSRAL $4, X0
	PACKSSLW X0, X0
	MOVL (DI), AX
	MOVD AX, X1
	PMOVZXBW X1, X1
	PADDW X0, X1
	PACKUSWB X1, X1
	MOVD X1, AX
	MOVL AX, (DI)
	ADDQ $16, SI
	ADDQ R8, DI
	DECQ CX
	JNZ residual4Row
	RET

