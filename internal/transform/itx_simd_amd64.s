	PSUBL X4, X12
	PMULLD ·dctK181<>(SB), X12
	PADDL ·dctRound128<>(SB), X12
	PSRAL $8, X12
	PADDL X4, X7
	PMULLD ·dctK181<>(SB), X7
	PADDL ·dctRound128<>(SB), X7
	PSRAL $8, X7

