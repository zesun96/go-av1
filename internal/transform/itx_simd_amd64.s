	PMULLD ·dctK1703<>(SB), X8
	PADDL X8, X6
	PADDL ·dctRound1024<>(SB), X6
	PSRAL $11, X6

	// Odd t7a.
	MOVOU 32(SI), X7
	MOVO X7, X8
	PMULLD ·dctKN79<>(SB), X7
	MOVOU 224(SI), X9
	PMULLD ·dctK799<>(SB), X9
	PADDL X9, X7
	PADDL ·dctRound2048<>(SB), X7
	PSRAL $12, X7
	PADDL X8, X7

